/** Boot grammars statically imported by ui-primitives' highlight.ts (vendor chunk; lazy ones stay on-demand). */
const BOOT_GRAMMAR_FILES = ['dist/typescript.mjs', 'dist/shellscript.mjs', 'dist/json.mjs']

/** Font asset extensions routed to assets/fonts/ (KaTeX faces). */
const FONT_EXTENSIONS = ['.woff2', '.woff', '.ttf']

function npmPackageOf(id) {
  const parts = id.split('/node_modules/')
  if (parts.length === 1) return undefined
  const [first, second] = parts[parts.length - 1].split('/')
  if (first.startsWith('.')) return undefined
  if (first.startsWith('@')) return second === undefined ? undefined : `${first}/${second}`
  return first
}

