import { existsSync, realpathSync } from 'node:fs'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
import { defineConfig } from 'vite'
import react from '@vitejs/plugin-react'

/**
 * dsh-chamber renderer build (design 05 §2/§3.6, v4).
 *
 * The frontend is the dsh official web frontend, source-reused and self-built:
 * the shell entry (`index.html` → `src/main.tsx`) hosts the chamber chrome
 * (auth gate / instance sidebar / management view) and the dsh boot kernel
 * (AppWebEntry per instance); the `chamber` entry is the single boot-graph
 * plugin bundle (one entry registering every ui-* client plugin via
 * ctx.plugin()). This mirrors apps/web's vite configuration: workspace
 * packages resolve to SOURCE so CSS rides the vite pipeline, the vendored
 * cordis Loader gets its node-only import stubbed, and the heavy render
 * families split into a stable vendor chunk.
 *
 * There is no standalone serve: bare Vite cannot inject `window.__DSH_BOOT__`
 * (that is the control plane's job — it serves dist/ and injects the manifest
 * it reads from dist/manifest.json), so `vite serve` refuses to start.
 */

const src = (rel) => fileURLToPath(new URL(rel, import.meta.url))
const STANDALONE_ERROR = 'packages/renderer is not a standalone application: bare Vite cannot inject window.__DSH_BOOT__. '
  + 'The control plane serves the built dist/ and injects the boot manifest it reads from dist/manifest.json '
  + '(generated by scripts/gen-boot-manifest.mjs).'

/** Fail before a Vite dev or preview server can expose the boot-manifest-free shell. */
function rejectStandaloneServe() {
  return {
    name: 'dsh-chamber-reject-standalone-serve',
    config(_config, env) {
      if (env.command === 'serve') throw new Error(STANDALONE_ERROR)
    },
  }
}

/**
 * @deepseek-ai/* workspace resolution to SOURCE (mirrors apps/web's alias
 * list, extended to every package the chamber bundle imports). The vendor
 * tree (`vendor/harness-packages/@deepseek-ai`) is a read-only directory of
 * symlinks into the external dsh checkout; the three chamber-copied packages
 * (connection, web, the self-built ui-sidebar — the only dsh source we may
 * modify) resolve to our copies. Subpaths map onto the source tree by
 * convention (`<pkg>/client` → `src/client/index.ts`, …); dsh-host-apiproxy's
 * export map diverges (./client → src/fetch/client.ts, ./api/* → src/api/*.ts)
 * and is special-cased. The chamber sidebar plugin resolves through the
 * resolve.alias table (`@dsh-chamber/*` row).
 */
/**
 * Bare (non-workspace) npm specifiers imported from vendor source: node
 * resolution walks up from the vendor directory (the external dsh checkout,
 * which carries no node_modules), so every such import is resolved from the
 * renderer's own install tree instead (declared in packages/renderer
 * devDependencies — the bundler-consumer pattern apps/web uses). Workspace
 * (@deepseek-ai) and relative specifiers are left to the other plugins.
 */
const requireFromRenderer = createRequire(import.meta.url)

function npmFallback() {
  return {
    name: 'dsh-chamber-npm-fallback',
    enforce: 'pre',
    resolveId(specifier) {
      if (typeof specifier !== 'string') return undefined
      if (specifier.startsWith('.') || specifier.startsWith('/') || specifier.startsWith('node:')
        || specifier.startsWith('@deepseek-ai/')) return undefined
      try {
        return requireFromRenderer.resolve(specifier)
      } catch {
        return undefined
      }
    },
  }
}

function deepseekSource() {
  return {
    name: 'dsh-chamber-deepseek-source',
    enforce: 'pre',
    resolveId(specifier) {
      if (typeof specifier !== 'string' || !specifier.startsWith('@deepseek-ai/')) return undefined
      const rest = specifier.slice('@deepseek-ai/'.length)
      const slash = rest.indexOf('/')
      const name = slash === -1 ? rest : rest.slice(0, slash)
      const sub = slash === -1 ? '' : rest.slice(slash + 1)
      const pick = (...cands) => cands.find((c) => c !== undefined && existsSync(c))
      const real = (p) => realpathSync(p)
      if (name === 'dsh-client-connection' || name === 'dsh-client-web') {
        const base = new URL(`../${name}/src/`, import.meta.url)
        return pick(
          sub === '' ? fileURLToPath(new URL('index.ts', base)) : undefined,
          sub === 'client' ? fileURLToPath(new URL('client/index.ts', base)) : undefined,
        )
      }
      // The `/remote` subpath of typert-contributing packages has no upstream
      // source (src/remote/index.ts does not exist): it resolves to the
      // generator's artifact instead (gen-typert-remotes.mjs writes it from
      // the host face model, mirroring the upstream tsdown output).
      if (sub === 'remote') {
        const artifact = fileURLToPath(new URL(`./src/generated/typert/${name}/typert.remote-client.js`, import.meta.url))
        const hit = pick(artifact)
        if (hit !== undefined) return real(hit)
        return undefined
      }
      const pkgUrl = new URL(`${name}/`, new URL('../../vendor/harness-packages/@deepseek-ai/', import.meta.url))
      if (!existsSync(pkgUrl)) return undefined
      const srcdir = fileURLToPath(new URL('src/', pkgUrl))
      const pickReal = (...cands) => {
        const hit = pick(...cands)
        return hit === undefined ? undefined : real(hit)
      }
      if (sub === '') return pickReal(`${srcdir}index.ts`)
      if (name === 'dsh-host-apiproxy') {
        if (sub === 'client') return pickReal(`${srcdir}fetch/client.ts`)
        if (sub === 'api') return pickReal(`${srcdir}api/index.ts`)
        if (sub.startsWith('api/')) return pickReal(`${srcdir}${sub}.ts`)
        return undefined
      }
      // Vendor `./src/*` deep subpaths (the canonical export-map form the
      // chamber ui-layout fork imports, e.g.
      // `@deepseek-ai/dsh-client-ui-layout/src/client/AppFrame.tsx`): the
      // specifier already names the src/ directory, so strip the redundant
      // prefix before joining the source tree.
      if (sub.startsWith('src/')) return pickReal(`${srcdir}${sub.slice(4)}`)
      return pickReal(
        `${srcdir}${sub}/index.ts`,
        `${srcdir}${sub}.ts`,
        `${srcdir}${sub}/index.tsx`,
        `${srcdir}${sub}.tsx`,
        // Non-TS deep subpaths (CSS via `./src/*`-style exports and literal
        // source files): resolved straight into the source tree. The `./styles`
        // export of e.g. dsh-client-ui-theme points at the BUILT lib/ tree,
        // which the source-only vendor cannot provide.
        `${srcdir}${sub}`,
      )
    },
  }
}

/**
 * Vendor-chunk membership, by exact npm package name — copied from apps/web
 * (math/highlight/markdown families; only packages workspace code imports
 * DIRECTLY need listing — rollup's chunk coloring pulls the private
 * transitive deps in automatically). Every member must be React-free.
 */
