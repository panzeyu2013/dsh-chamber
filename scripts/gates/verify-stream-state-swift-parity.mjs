/**
 * Swift parity gate.
 *
 * Compiles the Swift mirror (`packages/dsh-stream-state/swift/CarrierDecision.swift`)
 * with a generated assertions file and runs it against the shared
 * `packages/dsh-stream-state/tables.json`. The mirror and the TS reducer must agree
 * on the same table, or the shell and the page will disagree about when to rebuild
 * a carrier - the class of drift this gate exists to remove.
 *
 * CI VARIANTS:
 *   node scripts/gates/verify-stream-state-swift-parity.mjs            # local: real assertions
 *   ... --simulate-skip                                                # negative control
 *   DSH_CHAMBER_SWIFT_PARITY_SKIP=1 ...                                # explicit loud skip
 *
 * A `swiftc` that is missing or cannot compile this Foundation-only file is a
 * FAILURE, not a silent skip: the file is deliberately platform-neutral, so a
 * compile error means the mirror broke. The only sanctioned skip is the explicit
 * env var, and it prints that it skipped.
 */
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { spawnSync } from 'node:child_process'

const HERE = dirname(fileURLToPath(import.meta.url))
const REPO_ROOT = join(HERE, '..', '..')
const PACKAGE = join(REPO_ROOT, 'packages', 'dsh-stream-state')
const MIRROR = join(PACKAGE, 'swift', 'CarrierDecision.swift')
/** The shell's load state machine mirrors the TS reducer the same way. Both
 *  sources compile into the one assertions binary, so a drift in either fails here. */
const LOAD_MIRROR = join(PACKAGE, 'swift', 'LoadState.swift')
/** The phase names are the contract shared with `src/load-state.ts`: the lockstep
 *  below fails if either side gains, loses or renames a phase. */
export const LOAD_PHASES = ['cold', 'probing', 'loading', 'loaded', 'retrying', 'failurePage']
const TABLES = join(PACKAGE, 'tables.json')

export const SWIFT_PARITY_SKIP_ENV = 'DSH_CHAMBER_SWIFT_PARITY_SKIP'

/** The assertions the mirror must satisfy. Exported so a test can assert the
 * corpus is non-empty (a gate that checks nothing must not read as green). */
export function swiftAssertions(tablesPath) {
  return [
    '// GENERATED by scripts/gates/verify-stream-state-swift-parity.mjs - do not edit.',
    'import Foundation',
    '',
    'var failures = 0',
    'func check(_ name: String, _ condition: Bool) {',
    '    if !condition { failures += 1; FileHandle.standardError.write(Data(("FAIL " + name + "\\n").utf8)) }',
    '}',
    '',
    'let tables = try CarrierTables.load(from: URL(fileURLWithPath: ' + JSON.stringify(tablesPath) + '))',
    // ---- B5: LoadState (the three real-machine defects + the generation fence) ----
    'var ls = LoadState.initial',
    'let env = LoadEnv(probeStrikeLimit: 3, retryLimit: 2, progressSlaMs: 15000)',
    'check("load: starts cold", ls.phase == .cold)',
    'ls = LoadStateMachine.reduce(ls, .generationStarted(generation: 1, at: 0), env).state',
    'ls = LoadStateMachine.reduce(ls, .loadStarted(generation: 1, at: 10), env).state',
    'check("load: loading after loadStarted", ls.phase == .loading)',
    'check("defect2: a committed load is not content", !ls.contentIsBelievable)',
    'ls = LoadStateMachine.reduce(ls, .contentAlive(generation: 1, at: 20), env).state',
    'check("load: content is believable once loaded", ls.contentIsBelievable)',
    'let restarted = LoadStateMachine.reduce(ls, .generationStarted(generation: 2, at: 100), env).state',
    'check("defect1: a new generation re-enters cold (no permanent latch)", restarted.phase == .cold)',
    'let reloading = LoadStateMachine.reduce(restarted, .loadStarted(generation: 2, at: 110), env).state',
    'check("defect1: and it may load again", reloading.phase == .loading)',
    'let fenced = LoadStateMachine.reduce(reloading, .contentAlive(generation: 1, at: 111), env).state',
    'check("fence: a stale generation cannot claim content", !fenced.contentIsBelievable)',
    'var probe = LoadStateMachine.reduce(LoadState.initial, .generationStarted(generation: 3, at: 0), env).state',
    'let oneStrike = LoadStateMachine.reduce(probe, .probeFailed(generation: 3, at: 1), env)',
    'check("defect3: one failed probe is not a success", oneStrike.state.phase != .loaded && oneStrike.state.probeStrikes == 1)',
    'probe = oneStrike.state',
    'probe = LoadStateMachine.reduce(probe, .probeFailed(generation: 3, at: 2), env).state',
    'let atLimit = LoadStateMachine.reduce(probe, .probeFailed(generation: 3, at: 3), env)',
    'check("defect3: the strike limit moves to retrying", atLimit.state.phase == .retrying)',
    'check("defect3: and asks for recovery", atLimit.effects.contains(.scheduleRecovery(generation: 3)))',
    'let cleared = LoadStateMachine.reduce(atLimit.state, .probeSucceeded(generation: 3, at: 4), env).state',
    'check("a success clears the strikes", cleared.probeStrikes == 0 && cleared.phase == .loaded)',
    'let crashed = LoadStateMachine.reduce(cleared, .recoveryScheduled(generation: 3, at: 5), env).state',
    'check("crash recovery is in flight", crashed.recoveringFromCrash)',
    'let shown = LoadStateMachine.reduce(crashed, .recoveryFailed(generation: 3, at: 6), env)',
    'check("the failure page is shown once", shown.state.phase == .failurePage && shown.effects.contains(.showFailurePage))',
    'let again = LoadStateMachine.reduce(shown.state, .recoveryFailed(generation: 3, at: 7), env)',
    'check("the give-up gate is one-shot per generation", !again.effects.contains(.showFailurePage))',
    'let nextGen = LoadStateMachine.reduce(again.state, .generationStarted(generation: 4, at: 8), env).state',
    'check("a new generation earns its own gate", !nextGen.giveUpSpent)',
    'let loading = LoadStateMachine.reduce(nextGen, .loadStarted(generation: 4, at: 1000), env).state',
    'check("SLA: the boundary is not late", !loading.isLate(now: 16000, env: env))',
    'check("SLA: past the bound is late", loading.isLate(now: 16001, env: env))',
    'check("SLA: an idle shell is never late", !LoadState.initial.isLate(now: 1e9, env: env))',
    'check("ladder[0]=30s", CarrierDecision.openingBudgetMs(streak: 0, tables: tables) == 30000)',
    'check("ladder[1]=60s", CarrierDecision.openingBudgetMs(streak: 1, tables: tables) == 60000)',
    'check("ladder[2]=120s", CarrierDecision.openingBudgetMs(streak: 2, tables: tables) == 120000)',
    'check("ladder[3]=240s", CarrierDecision.openingBudgetMs(streak: 3, tables: tables) == 240000)',
    'check("ladder[4]=300s", CarrierDecision.openingBudgetMs(streak: 4, tables: tables) == 300000)',
    'check("ladder capped", CarrierDecision.openingBudgetMs(streak: 99, tables: tables) == 300000)',
    'check("ladder degenerate", CarrierDecision.openingBudgetMs(streak: -1, tables: tables) == 30000)',
    'check("rebuild admitted at t=0", CarrierDecision.shouldRebuild(phaseClosed: false, pendingRebuildInFlight: false, rebuildsAt: [], at: 0, tables: tables))',
    'check("rebuild denied inside spacing", !CarrierDecision.shouldRebuild(phaseClosed: false, pendingRebuildInFlight: true, rebuildsAt: [0], at: 500, tables: tables))',
    'check("rebuild denied in same window", !CarrierDecision.shouldRebuild(phaseClosed: false, pendingRebuildInFlight: false, rebuildsAt: [0], at: 30000, tables: tables))',
    'check("rebuild admitted at window edge", CarrierDecision.shouldRebuild(phaseClosed: false, pendingRebuildInFlight: false, rebuildsAt: [0], at: 60000, tables: tables))',
    'check("closed carrier never rebuilds", !CarrierDecision.shouldRebuild(phaseClosed: true, pendingRebuildInFlight: false, rebuildsAt: [], at: 0, tables: tables))',
    // G-F: the TS reducer refuses an unusable clock (decideRebuild: !isFinite(at) =>
    // false). The mirror must agree, or the shell rebuilds the carrier on a clock
    // the page would hold on.
    'check("NaN at never rebuilds", !CarrierDecision.shouldRebuild(phaseClosed: false, pendingRebuildInFlight: false, rebuildsAt: [], at: Double.nan, tables: tables))',
    'check("+inf at never rebuilds", !CarrierDecision.shouldRebuild(phaseClosed: false, pendingRebuildInFlight: false, rebuildsAt: [], at: Double.infinity, tables: tables))',
    'check("-inf at never rebuilds", !CarrierDecision.shouldRebuild(phaseClosed: false, pendingRebuildInFlight: false, rebuildsAt: [], at: -Double.infinity, tables: tables))',
    // G-B in Swift: the progress SLA only applies while the shell is LOADING. The
    // probeSucceeded path leaves loadingSinceMs behind, so "late" must be a phase
    // predicate, not a timestamp predicate.
    'check("a settled shell is never late", !cleared.isLate(now: 1000000, env: env))',
    'check("stall denied below streak", !CarrierDecision.stallEscalationAllowed(streak: 1, tables: tables))',
    'check("stall allowed at streak", CarrierDecision.stallEscalationAllowed(streak: 2, tables: tables))',
    'check("teardown silent on zero frames + long life", CarrierDecision.teardownMayJudgeSilent(frameDelta: 0, streamLifeMs: 20000, tables: tables))',
    'check("teardown silent denied on short life", !CarrierDecision.teardownMayJudgeSilent(frameDelta: 0, streamLifeMs: 5000, tables: tables))',
    'check("teardown silent denied when frames arrived", !CarrierDecision.teardownMayJudgeSilent(frameDelta: 3, streamLifeMs: 20000, tables: tables))',
    'check("non-finite delta never judges", !CarrierDecision.teardownMayJudgeSilent(frameDelta: Double.nan, streamLifeMs: 20000, tables: tables))',
    'if failures > 0 { FileHandle.standardError.write(Data("swift-parity: \\(failures) assertion(s) failed\\n".utf8)); exit(1) }',
    'print("swift-parity: all assertions passed")',
    '',
  ].join('\n')
}

function fail(message) {
  console.error('[swift-parity] ' + message)
  process.exit(1)
}

function main() {
  if (process.argv.includes('--simulate-skip')) {
    console.log('[swift-parity] SKIPPED (simulate-skip) - this flag must never appear in a release path')
    return
  }
  if (process.env[SWIFT_PARITY_SKIP_ENV] === '1') {
    console.log('[swift-parity] SKIPPED via ' + SWIFT_PARITY_SKIP_ENV + '=1 (explicit, loud)')
    return
  }
  if (!existsSync(MIRROR)) fail('Swift mirror missing: ' + MIRROR)
  if (!existsSync(LOAD_MIRROR)) fail('Swift load mirror missing: ' + LOAD_MIRROR)
  const tsLoad = readFileSync(join(PACKAGE, 'src', 'load-state.ts'), 'utf8')
  const swiftLoad = readFileSync(LOAD_MIRROR, 'utf8')
  for (const phase of LOAD_PHASES) {
    // Bidirectional: the TS union must still name it, and the Swift mirror must still
    // declare it. A rename on one side alone is exactly the drift this gate exists for.
    if (!tsLoad.includes("'" + phase + "'")) fail('load phase missing from the TS union: ' + phase)
    if (!swiftLoad.includes('case ' + phase)) fail('load phase missing from the Swift mirror: ' + phase)
  }
  if (!existsSync(TABLES)) fail('shared tables missing: ' + TABLES)
  const dir = mkdtempSync(join(tmpdir(), 'swift-parity-'))
  try {
    const main = join(dir, 'main.swift')
    writeFileSync(main, swiftAssertions(TABLES), 'utf8')
    const out = join(dir, 'parity')
    // A hermetic module cache inside the temp dir: sandboxed/file-restricted
    // environments have a read-only ~/.cache/clang, and swiftc fails there with
    // "could not build C module 'SwiftShims'" - a tooling restriction, not a
    // defect in the mirror.
    const cache = join(dir, 'module-cache')
    mkdirSync(cache, { recursive: true })
    const compile = spawnSync(
      'swiftc',
      ['-O', '-module-cache-path', cache, '-o', out, MIRROR, LOAD_MIRROR, main],
      { encoding: 'utf8' },
    )
    if (compile.status !== 0) {
      process.stdout.write(compile.stdout ?? '')
      process.stderr.write(compile.stderr ?? '')
      fail('swiftc could not compile the platform-neutral mirror (exit ' + String(compile.status ?? 'null') + ')')
    }
    const run = spawnSync(out, [], { encoding: 'utf8' })
    process.stdout.write(run.stdout ?? '')
    process.stderr.write(run.stderr ?? '')
    if (run.status !== 0) fail('swift assertions failed (exit ' + String(run.status ?? 'null') + ')')
  } finally {
    rmSync(dir, { recursive: true, force: true })
  }
}

if (process.argv[1] && process.argv[1].endsWith('verify-stream-state-swift-parity.mjs')) main()
